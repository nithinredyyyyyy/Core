function getPlacementPoints(p) {
  if (p === 1) return 10; if (p === 2) return 6; if (p === 3) return 5;
  if (p === 4) return 4;  if (p === 5) return 3; if (p === 6) return 2;
  if (p === 7) return 1;  if (p === 8) return 1; return 0;
}

function buildStandings(raw, gameCount) {
  return raw.map(([rank, team, total, ...gameArr]) => {
    const games = gameArr.slice(0, gameCount);
    let matches = 0, wwcd = 0, pos = 0, elimins = 0;
    const mCols = {};
    games.forEach((game, idx) => {
      if (game) {
        matches++;
        if (game.placement === 1) wwcd++;
        const pPts = getPlacementPoints(game.placement);
        pos += pPts;
        elimins += game.kills;
        mCols[`m${idx + 1}`] = pPts + game.kills;
      }
    });
    return {
      placement: rank,
      team,
      fullTeam: team,
      points: total,
      outcome: "Stage result",
      matches, wwcd, pos, elimins,
      ...mCols
    };
  });
}

