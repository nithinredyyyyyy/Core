export function buildBmps2026OverallPlayerStats(stages) {
  const rowsByPlayer = new Map();
  for (const entry of stages.flat()) {
    const key = `${String(entry.teamName || "").toLowerCase()}::${String(entry.player || "").toLowerCase()}`;
    const existing =
      rowsByPlayer.get(key) || {
        ...entry,
        rank: 0,
        finishes: 0,
        matches: 0,
        best: 0,
        fivePlusFinishes: 0,
        erangel: 0,
        miramar: 0,
        rondo: 0,
        contributionTotal: 0,
        contributionWeight: 0,
      };
    const matches = Number(entry.matches) || 0;
    const contribution = Number(String(entry.contribution || "").replace("%", "")) || 0;
    existing.finishes += Number(entry.finishes) || 0;
    existing.matches += matches;
    existing.best = Math.max(existing.best || 0, Number(entry.best) || 0);
    existing.fivePlusFinishes += Number(entry.fivePlusFinishes) || 0;
    existing.erangel += Number(entry.erangel) || 0;
    existing.miramar += Number(entry.miramar) || 0;
    existing.rondo += Number(entry.rondo) || 0;
    existing.contributionTotal += contribution * matches;
    existing.contributionWeight += matches;
    rowsByPlayer.set(key, existing);
  }

  return [...rowsByPlayer.values()]
    .map((entry) => ({
      ...entry,
      fpm: entry.matches > 0 ? (entry.finishes / entry.matches).toFixed(2) : "0.00",
      contribution:
        entry.contributionWeight > 0
          ? `${Math.round(entry.contributionTotal / entry.contributionWeight)}%`
          : "0%",
    }))
    .toSorted((left, right) => {
      if (right.finishes !== left.finishes) return right.finishes - left.finishes;
      const fpmDelta = Number(right.fpm) - Number(left.fpm);
      if (fpmDelta !== 0) return fpmDelta;
      return String(left.player || "").localeCompare(String(right.player || ""));
    })
    .map((entry, index) => ({
      ...entry,
      rank: index + 1,
    }));
}

